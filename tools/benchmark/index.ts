/**
 * Caladia performance benchmark.
 *
 * Generates synthetic linear-chain projects of various sizes and measures:
 *   - Single `schedule()` call (CPM)
 *   - `simulate({ iterations: 1000 })` (Monte Carlo)
 *
 * Produces `diagram-health-thresholds.json` at the repo root which the app
 * reads to colour the diagram-health indicator in the Toolbar.
 *
 * Usage:
 *   pnpm --filter @procsim/benchmark bench
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { schedule, type ScheduleInput } from '@procsim/scheduler';
import { simulate } from '@procsim/simulation';
import type { ProjectNode, ProjectEdge } from '@procsim/file-format';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..', '..');

// ── Synthetic project generator ───────────────────────────────────────────────

function makeLinearChain(n: number): ScheduleInput {
  const nodes: ProjectNode[] = [];
  const edges: ProjectEdge[] = [];

  for (let i = 0; i < n; i++) {
    nodes.push({
      id: `n${i}`,
      nodeType: 'activity',
      name: `Activity ${i}`,
      duration: { value: 8, unit: 'hours' },
      position: { x: i * 200, y: 100 },
      calendarId: null,
      consumesResources: false,
      resourceAssignments: [],
      // No distribution — constant-duration nodes exercise the MC scheduling
      // loop (the hot path) without needing the sampler. Sampler overhead
      // is small relative to the schedule() cost per iteration.
    });
    if (i > 0) {
      edges.push({
        id: `e${i}`,
        from: `n${i - 1}`,
        to: `n${i}`,
        type: 'FS',
        lag: { value: 0, unit: 'hours' },
      });
    }
  }

  return {
    project: {
      name: `Bench-${n}`,
      startDate: '2024-01-01',
      defaultCalendarId: 'c0',
      displayUnit: 'days',
    },
    nodes,
    edges,
    resources: [],
    calendars: [
      {
        id: 'c0',
        name: 'Standard',
        workingDays: [false, true, true, true, true, true, false],
        hoursPerDay: 8,
        daysPerWeek: 5,
        holidayPreset: 'NONE',
        holidayPresetVersion: '',
        exceptions: [],
      },
    ],
    loops: [],
  };
}

// ── Measurement helpers ───────────────────────────────────────────────────────

function median(samples: number[]): number {
  const sorted = [...samples].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? (sorted[mid - 1]! + sorted[mid]!) / 2 : sorted[mid]!;
}

function measureMs(fn: () => void, runs = 5): number {
  const samples: number[] = [];
  for (let i = 0; i < runs; i++) {
    const t0 = performance.now();
    fn();
    samples.push(performance.now() - t0);
  }
  return median(samples);
}

// ── Run benchmarks ────────────────────────────────────────────────────────────

// Note: the recursive DFS in cpm.ts overflows for very large linear chains
// (~5000 nodes deep). Real projects are rarely pure linear chains at that
// depth; meaningful thresholds come from the 100–2000 range.
const SIZES = [100, 250, 500, 1000, 2000];
const MC_ITERATIONS = 1000;

interface BenchResult {
  n: number;
  scheduleMs: number;
  simulateMs: number;
}

const results: BenchResult[] = [];

for (const n of SIZES) {
  process.stdout.write(`  n=${n.toString().padStart(4)}  `);
  const input = makeLinearChain(n);

  const scheduleMs = measureMs(() => schedule(input));
  process.stdout.write(`schedule: ${scheduleMs.toFixed(1)}ms  `);

  const simulateMs = measureMs(() =>
    simulate({ schedule: input, iterations: MC_ITERATIONS, seed: 42 }),
  );
  process.stdout.write(`simulate(${MC_ITERATIONS}): ${simulateMs.toFixed(1)}ms\n`);

  results.push({ n, scheduleMs, simulateMs });
}

// ── Derive thresholds ─────────────────────────────────────────────────────────
// amber = smallest N where schedule() takes >5ms    (perceptible on keystroke)
// red   = smallest N where schedule() takes >15ms   (definitely sluggish)
// If neither threshold is reached, use the 80th / 100th percentile of measured sizes.

const AMBER_SCHEDULE_MS = 5;
const RED_SCHEDULE_MS = 15;

function findThreshold(targetMs: number, fallbackIdx: number): number {
  const hit = results.find((r) => r.scheduleMs >= targetMs);
  if (hit) return hit.n;
  // Fallback: use a position in the measured size array
  return results[Math.min(fallbackIdx, results.length - 1)]!.n;
}

const amber = findThreshold(AMBER_SCHEDULE_MS, Math.ceil(results.length * 0.6));
const red = findThreshold(RED_SCHEDULE_MS, results.length - 1);

const thresholds = {
  _comment:
    'Auto-generated by tools/benchmark — do not edit by hand. Re-run `pnpm --filter @procsim/benchmark bench` to refresh.',
  amber,
  red,
  results,
};

const outPath = resolve(REPO_ROOT, 'diagram-health-thresholds.json');
writeFileSync(outPath, JSON.stringify(thresholds, null, 2) + '\n');

console.log(`\nThresholds: amber=${amber} nodes  red=${red} nodes`);
console.log(`Written → ${outPath}`);
